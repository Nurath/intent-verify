#!/usr/bin/env python3
"""Does the criteria agent ask first only where it should?

Since 0.5.0 one ambiguity may be marked "whether": true. It means that on the
other reading the request did not ask for a change at all, and it is put to the
user before the verifier runs. Asked too rarely, a change nobody requested is
verified for minutes and comes back MATCHES INTENT. Asked too often, every run
starts with a question again: 0.3.1 put 41 to the user on 16 one-line requests.

This runs stage 1 alone (no code, no verifier) on two sets:

    python3 benchmark/ask_first.py --model claude-sonnet-5-5 --repeat 3

  - benchmark/ask_first_cases.json, each request --repeat times, since the
    same request does not always get the same answer: requests that may not ask
    for a change (expected: marked), requests that ask for one in the form of a
    question or a wish (expected: not marked), and requests a careful reader
    could take either way (not scored, reported);
  - every request in benchmark/cases.json, once: all of them plainly ask for a
    change (expected: not marked). --own-only leaves these out.
"""
import argparse
import datetime as _dt
import json
import os
import re
import sys

import run_bench  # puts tools/ on sys.path and makes the streams UTF-8

EXPECTED = {True: "marked", False: "not marked", None: "either"}


def asks_first(manifest):
    return any(a.get("whether") for a in (manifest or {}).get("ambiguities", []))


def main(argv=None):
    ap = argparse.ArgumentParser(description="stage 1 only: is the ask-first mark used where it should be")
    ap.add_argument("--model", required=True)
    ap.add_argument("--repeat", type=int, default=1, help="runs of each request in ask_first_cases.json")
    ap.add_argument("--timeout", type=int, default=300, help="per-call seconds")
    ap.add_argument("--no-write", action="store_true")
    ap.add_argument("--own-only", action="store_true", help="skip the requests of benchmark/cases.json")
    a = ap.parse_args(argv)

    own = json.loads(run_bench._read(os.path.join(run_bench.HERE, "ask_first_cases.json")))["cases"]
    plain = [{"id": c["id"], "ask": False, "request": c["request"], "set": c["suite"]}
             for c in json.loads(run_bench._read(os.path.join(run_bench.HERE, "cases.json")))["cases"]]
    cases = [dict(c, set="ask-first", runs=a.repeat) for c in own] + ([] if a.own_only else [dict(c, runs=1) for c in plain])

    rows, first_call = [], len(run_bench.USAGE)
    for c in cases:
        row = {"case": c, "marked": 0, "invalid": 0, "replies": [], "question": ""}
        for _ in range(c["runs"]):
            manifest, replies = run_bench.derive_manifest(c, a.model, a.timeout)
            row["replies"].append(replies)
            row["invalid"] += manifest is None
            if asks_first(manifest):
                row["marked"] += 1
                row["question"] = next(x["question"] for x in manifest["ambiguities"] if x.get("whether"))
        rows.append(row)
        print("%-22s expected=%-10s marked %d/%d%s" % (c["id"], EXPECTED[c["ask"]], row["marked"], c["runs"],
                                                      "  NO VALID MANIFEST x%d" % row["invalid"] if row["invalid"] else ""))
    calls = run_bench.USAGE[first_call:]

    def tally(group):
        return sum(r["marked"] for r in group), sum(r["case"]["runs"] for r in group)

    groups = [("may not ask for a change", [r for r in rows if r["case"]["ask"] is True], "all"),
              ("ask for one as a question or a wish", [r for r in rows if r["case"]["ask"] is False and r["case"]["set"] == "ask-first"], "none"),
              ("a careful reader could take either way", [r for r in rows if r["case"]["ask"] is None], "not scored"),
              ("the benchmark's own, plainly asking for a change", [r for r in rows if r["case"]["set"] != "ask-first"], "none")]
    stamp = _dt.date.today().isoformat()
    out = ["# Ask first — %s — stage 1 on %s\n" % (stamp, a.model),
           "Is the one ambiguity that is asked before verifying (`\"whether\": true`) marked where the words may",
           "not ask for a change, and only there? Each call is `claude -p --safe-mode --effort %s` with every" % run_bench.EFFORT,
           "tool disabled. Requests of `ask_first_cases.json` were each run %d time(s), the benchmark's own once." % a.repeat,
           "Generated by `benchmark/ask_first.py`.\n",
           "| requests | runs marked | expected |\n|---|---|---|"]
    out += ["| %s (%d) | %d/%d | %s |" % ((name, len(group)) + tally(group) + (want,)) for name, group, want in groups if group]
    out += ["| runs with no valid manifest after the one retry | %d | 0 |" % sum(r["invalid"] for r in rows),
            "| model calls | %d | |" % len(calls),
            "| cost, USD at list price | %.2f | |" % sum(u["cost_usd"] for u in calls),
            "| seconds per call, median | %.1f | |" % (sorted(u["seconds"] for u in calls)[len(calls) // 2] if calls else 0),
            "\n| request | set | expected | runs marked | the question, where one was marked |\n|---|---|---|---|---|"]
    for r in rows:
        out.append("| %s | %s | %s | %d/%d | %s |" % (r["case"]["id"], r["case"]["set"], EXPECTED[r["case"]["ask"]], r["marked"],
                                                    r["case"]["runs"], r["question"][:170].replace("|", "/")))
    report = "\n".join(out) + "\n"
    print(report)
    wrong = sum(1 for r in rows if r["invalid"] or (r["case"]["ask"] is True and r["marked"] < r["case"]["runs"])
                or (r["case"]["ask"] is False and r["marked"]))
    if not a.no_write:
        name = "%s-ask-first-%s" % (stamp, re.sub(r"[^A-Za-z0-9._-]", "_", a.model))
        dest = os.path.join(run_bench.HERE, "results", name + ".md")
        with open(dest, "w", encoding="utf-8") as f:
            f.write(report)
        raw = dest[:-3] + ".raw"
        os.makedirs(raw, exist_ok=True)
        for r in rows:
            for run, replies in enumerate(r["replies"]):
                for attempt, text in enumerate(replies):
                    with open(os.path.join(raw, "%s.run%d.criteria.%d.txt" % (r["case"]["id"], run, attempt)), "w", encoding="utf-8") as f:
                        f.write(text or "")
        print("written: %s" % os.path.relpath(dest, run_bench.ROOT), file=sys.stderr)
    return 1 if wrong else 0


if __name__ == "__main__":
    sys.exit(main())
